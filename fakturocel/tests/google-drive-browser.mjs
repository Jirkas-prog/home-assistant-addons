import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs/promises';
import { credentials } from './google-drive-fixture.mjs';
import { readBackupFile } from '../server/backup-formats.mjs';
import { unpackBackup } from '../src/model.js';

export async function exerciseGoogleDrive({ page, click, fill, choose, closed, acceptMessage, app, google, root, progress, czech }) {
  await click('nav:settings');
  await click('googleDrive');
  await page.locator('#modal').getByRole('heading', { name: 'Google Drive backups', exact: true }).waitFor();
  const englishActions = await page.locator('#modal [data-action]').evaluateAll(nodes => nodes.map(n => n.dataset.action));
  const englishFields = await page.locator('#modal [name]').evaluateAll(nodes => nodes.map(n => n.name));
  await click('closeModal');
  await choose('appLanguage', 'cs');
  await page.waitForFunction(() => document.documentElement.lang === 'cs');
  await click('googleDrive');
  await page.locator('#modal').getByRole('heading', { name: czech['Google Drive backups'], exact: true }).waitFor();
  assert.deepEqual(await page.locator('#modal [data-action]').evaluateAll(nodes => nodes.map(n => n.dataset.action)), englishActions);
  assert.deepEqual(await page.locator('#modal [name]').evaluateAll(nodes => nodes.map(n => n.name)), englishFields);
  await fill('clientId', credentials.clientId);
  await fill('clientSecret', credentials.clientSecret);
  await click('googleDriveConnect');
  await page.locator('#modal code').getByText('WWWWWWWWWWWWWWW', { exact: true }).waitFor();
  await page.locator('#modal').getByText(czech['Google account connected.'], { exact: true }).waitFor();
  assert.equal(app.googleDrive.status({ id: 'browser-owner' }).connected, true);
  await choose('enabled', 'true');
  await choose('format', 'both');
  await fill('intervalHours', 24);
  await fill('keepCount', 2);
  await click('googleDriveSave');
  await page.locator('#toast').getByText(czech['Google Drive backup settings saved.'], { exact: true }).waitFor();
  const fetchNormally = app.googleDrive.fetch;
  let uploadStarted;
  const uploading = new Promise(resolve => { uploadStarted = resolve; });
  app.googleDrive.fetch = (url, options = {}) => {
    if (options.method !== 'PUT') return fetchNormally(url, options);
    return new Promise((resolve, reject) => {
      uploadStarted();
      const abort = () => reject(Error('Synthetic cancelled cloud upload'));
      if (options.signal.aborted) abort();
      else options.signal.addEventListener('abort', abort, { once: true });
    });
  };
  await click('googleDriveBackup');
  await page.locator('#operationOverlay').getByRole('heading', { name: czech['Backing up to Google Drive'], exact: true }).waitFor();
  await uploading;
  assert(app.googleDrive.progress.percent >= 60 && app.googleDrive.progress.percent < 90);
  await page.keyboard.press('Escape');
  await page.locator('#operationOverlay').waitFor({ state: 'detached' });
  await page.locator('#toast').getByText(czech['Cloud backup cancelled. Application data is unchanged. Incomplete cloud copies are cleaned up after the next successful backup.'], { exact: true }).waitFor();
  assert.equal(app.googleDrive.busy, false);
  assert.equal(google.uploads.length, 0);
  app.googleDrive.fetch = fetchNormally;
  await click('googleDriveBackup');
  await page.locator('#toast').getByText(czech['The backup was uploaded and verified in Google Drive.'], { exact: true }).waitFor();
  assert.equal(google.uploads.length, 2);
  assert.deepEqual(google.files.map(f => f.appProperties.format).sort(), ['excel', 'zip']);
  assert.equal(google.files[0].appProperties.batch, google.files[1].appProperties.batch);
  await click('closeModal');
  await click('backupEncryption');
  assert.equal(await page.locator('#modal [name="download"],#modal [name="cloud"]').count(), 2);
  assert.equal(await page.locator('[name="local"]').inputValue(), 'false');
  assert.equal(await page.locator('[name="download"]').inputValue(), 'false');
  assert.equal(await page.locator('[name="cloud"]').inputValue(), 'false');
  await choose('local', 'true');
  await choose('download', 'true');
  await choose('cloud', 'true');
  await click('backupEncryptionSave');
  await closed();
  assert.deepEqual(app.store.backupEncryption(), { working: true, local: true, download: true, cloud: true });
  await click('googleDrive');
  await page.locator('#modal').getByText(czech['Cloud backup encryption is On. Keep the recovery-key PDF separately.'], { exact: true }).waitFor();
  await click('googleDriveBackup');
  await page.locator('#toast').getByText(czech['The backup was uploaded and verified in Google Drive.'], { exact: true }).waitFor();
  assert.equal(google.uploads.length, 4);
  assert(!google.uploads[3].subarray(0,2).equals(Buffer.from('PK')));
  await click('googleDriveRestore');
  await page.locator('[data-action^="cloudRestore:"]').first().waitFor();
  await page.locator('[data-action^="cloudRestore:"]').first().click();
  await page.locator('#messageOverlay').waitFor();
  await acceptMessage();
  await closed();
  assert(app.store.read().state.documents.length);
  await click('downloadBackup');
  await choose('format', 'both');
  const downloadEvent = page.waitForEvent('download');
  await click('backupExportSave');
  const file = path.join(root, 'complete-backup-set.zip');
  await (await downloadEvent).saveAs(file);
  const contents = await unpackBackup(await readBackupFile(app.store, await fs.readFile(file), 'complete-backup-set.zip'));
  assert.deepEqual(contents.data, app.store.read().state);
  assert(contents.blobs[contents.data.documents[0].pdfHash]);
  await closed();
  const chooser = page.waitForEvent('filechooser');
  await click('restore');
  await (await chooser).setFiles(file);
  await acceptMessage();
  await page.locator('#toast').getByText(czech['Backup has been restored.'], { exact: true }).waitFor();
  await click('googleDrive');
  await click('googleDriveDisconnect');
  await acceptMessage();
  await page.locator('#modal').getByText(czech['No Google account connected.'], { exact: true }).waitFor();
  assert.equal(app.store.meta('googleDrive'), null);
  assert.equal(google.files.length, 4);
  await click('closeModal');
  await closed();
  await choose('appLanguage', 'en');
  await page.waitForFunction(() => document.documentElement.lang === 'en');
  progress('PASS English/Czech cloud setup, per-location encryption, ZIP+Excel upload, cloud restore, complete local archive restore, and disconnect');
}
